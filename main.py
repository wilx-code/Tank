def on_forever():
    turret.set_position(hull.x, hull.y)
    spriteutils.place_angle_from(gun, spriteutils.angle_from(turret, aimer), 0, turret)
    transformSprites.rotate_sprite(turret,
        spriteutils.radians_to_degrees(spriteutils.angle_from(turret, aimer)))
    transformSprites.rotate_sprite(gun,
        spriteutils.radians_to_degrees(spriteutils.angle_from(turret, aimer)))
forever(on_forever)

def on_forever2():
    global deg
    if controller.left.is_pressed():
        deg += -1
    elif controller.right.is_pressed():
        deg += 1
    elif controller.up.is_pressed():
        pass
    transformSprites.rotate_sprite(hull, deg)
forever(on_forever2)
